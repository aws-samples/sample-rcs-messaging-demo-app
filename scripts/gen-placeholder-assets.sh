#!/bin/bash
set -euo pipefail
# Generate placeholder brand assets as SVG, then rasterize to PNG with
# rsvg-convert (brew install librsvg).
#
# The registration-critical logo + banner are generated PER BRAND, one pair per
# brand in the content/brand.md catalog, each written to that brand's own
# media/<id>/ folder (from its logoImage/bannerImage) in that brand's own
# accentColor, with its brandName monogram and tagline. The welcome cards use
# that per-brand banner. The shared, wordless card/product/vignette tiles and
# the favicon are drawn once; the favicon uses the default brand (defaultBrand).
# Nothing is hardcoded: brand values are read from content/brand.md.
#
# Two kinds of asset, generated by two different functions, because they have
# opposite requirements:
#
#   make_art   — card and product tiles. Deliberately WORDLESS. An earlier
#                version printed each tile's label into the image ("Prescriptions"),
#                which the card's own Title then repeated: on a real handset the
#                same word appeared twice, once in the artwork and once beneath
#                it, and Android's agent-profile media gallery aggregated a wall
#                of captioned tiles. Card media sits directly above card text, so
#                any text baked into it competes with the content layer. Tiles are
#                told apart by colour and composition instead.
#   make_label — the registration assets and the favicon, where a wordmark is the
#                point and nothing else renders alongside it.
#
# Replace them with real artwork later — the filenames and pixel sizes are what
# matter (logo 224x224 and banner 1440x448 are validated by RCS registration).
#
# Usage:  bash scripts/gen-placeholder-assets.sh

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
MEDIA="$ROOT/media"
STORE="$MEDIA/store"
WEBPUB="$ROOT/web/public"
BRAND_MD="$ROOT/content/brand.md"
# Last-resort accent, used only if a brand block has none. Per-brand generation
# sets ACCENT to each brand's own color before it draws that brand's assets.
ACCENT="#0B6E6F"
mkdir -p "$MEDIA" "$STORE" "$WEBPUB"

command -v rsvg-convert >/dev/null 2>&1 || { echo "ERROR: rsvg-convert not found. brew install librsvg"; exit 1; }

# ── Brand catalog parsing (content/brand.md frontmatter) ─────────────────────
# The source of truth is a brand catalog: a top-level `defaultBrand` scalar
# and a `brands:` map keyed by id, each block indented two spaces beneath it.
# These readers let the generator draw each brand's registration assets from
# that brand's own accentColor / brandName / tagline / logoImage / bannerImage,
# so the placeholder art and the catalog never disagree. No dependency beyond
# grep/sed/awk.

# A top-level scalar such as `defaultBrand: "anyhealth"`.
read_top_scalar() {
  grep -E "^[[:space:]]*$1:" "$BRAND_MD" 2>/dev/null | head -1 \
    | sed -E "s/^[[:space:]]*$1:[[:space:]]*//; s/[[:space:]]*#.*$//; s/^\"//; s/\"[[:space:]]*$//; s/^'//; s/'[[:space:]]*$//"
}

# One brand block's sub-key. Scans from `  <id>:` to the next 2-space sibling and
# reads `    <key>:`. A quoted value may contain "#" (a hex color), so a quoted
# span is taken verbatim; a bare value has a trailing " # comment" stripped.
read_brand_key() {
  local brand="$1" key="$2"
  awk -v brand="$brand" -v key="$key" '
    $0 ~ ("^  " brand ":[[:space:]]*$") { inblk=1; next }
    inblk {
      if ($0 ~ /^  [A-Za-z_]/ && $0 !~ /^    /) { exit }
      if ($0 ~ ("^    " key ":")) {
        line=$0
        sub(("^    " key ":[[:space:]]*"), "", line)
        if (line ~ /^"[^"]*"/) { sub(/^"/, "", line); sub(/".*$/, "", line) }
        else if (line ~ /^'"'"'[^'"'"']*'"'"'/) { sub(/^'"'"'/, "", line); sub(/'"'"'.*$/, "", line) }
        else { sub(/[[:space:]]+#.*$/, "", line); sub(/[[:space:]]+$/, "", line) }
        print line; exit
      }
    }
  ' "$BRAND_MD" 2>/dev/null
}

# The catalog brand ids, in file order: every `  <id>:` line under `brands:`.
brand_ids() {
  awk '
    /^brands:[[:space:]]*$/ { inbrands=1; next }
    inbrands {
      if ($0 ~ /^[A-Za-z_]/) { exit }                 # left the brands: map
      if ($0 ~ /^  [A-Za-z0-9_]+:[[:space:]]*$/) {    # a brand id line
        id=$0; sub(/^  /, "", id); sub(/:.*$/, "", id); print id
      }
    }
  ' "$BRAND_MD" 2>/dev/null
}

# First 1-2 characters of a brand name, uppercased, for the logo monogram.
monogram() {
  printf '%s' "$1" | sed -E 's/[^A-Za-z0-9].*$//' | cut -c1-2 | tr '[:lower:]' '[:upper:]'
}

# escape XML entities in labels
esc() { printf '%s' "$1" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g'; }

# Palette of accent-adjacent fields. Since tiles carry no text, colour is what
# makes one card distinguishable from the next in a carousel — so these are
# spread across the teal/blue/green/sand range rather than being shades of one
# hue. Each entry is "<base> <accentTone>".
PALETTE=(
  "#0B6E6F #7FD1C8"   # brand teal
  "#12595E #6FC3CF"   # deep teal
  "#1C6E8C #8ED0E8"   # slate blue
  "#2A5A7A #86B8D6"   # steel
  "#2E6B54 #8FD3B0"   # forest
  "#4A6B2E #C0D89A"   # olive
  "#7A5A2E #E2C69A"   # sand
  "#7A4550 #E0A9B2"   # clay
  "#5A4A7A #BEB0E0"   # iris
  "#245F72 #93CBD8"   # lagoon
)

# make_art <out.png> <w> <h> <palette index> <composition 0-3>
#
# A flat field with two large translucent shapes. No text, no gradients: it
# reads as intentional artwork at thumbnail size, stays under a few KB, and
# never fights the card Title rendered beneath it.
make_art() {
  local out="$1" w="$2" h="$3" idx="$4" comp="$5" base tone svg pair
  pair="${PALETTE[$(( idx % ${#PALETTE[@]} ))]}"
  base="${pair%% *}"; tone="${pair##* }"
  svg="$(mktemp -t ah_svg.XXXXXX).svg"
  {
    echo "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$w\" height=\"$h\" viewBox=\"0 0 $w $h\">"
    echo "  <rect width=\"$w\" height=\"$h\" fill=\"$base\"/>"
    case "$comp" in
      # Offset circle plus a bar, rotated through four arrangements so adjacent
      # cards in a carousel differ in layout as well as in colour.
      # Radii stay inside the frame on purpose: card media is cropped to fill,
      # and a shape already clipped by the image edge reads as a mistake once
      # the handset crops it again.
      0) echo "  <circle cx=\"$(( w * 70 / 100 ))\" cy=\"$(( h * 36 / 100 ))\" r=\"$(( h * 30 / 100 ))\" fill=\"$tone\" opacity=\"0.55\"/>"
         echo "  <rect x=\"0\" y=\"$(( h * 78 / 100 ))\" width=\"$w\" height=\"$(( h * 22 / 100 ))\" fill=\"$tone\" opacity=\"0.22\"/>" ;;
      1) echo "  <circle cx=\"$(( w * 30 / 100 ))\" cy=\"$(( h * 58 / 100 ))\" r=\"$(( h * 30 / 100 ))\" fill=\"$tone\" opacity=\"0.5\"/>"
         echo "  <rect x=\"$(( w * 66 / 100 ))\" y=\"0\" width=\"$(( w * 34 / 100 ))\" height=\"$h\" fill=\"$tone\" opacity=\"0.2\"/>" ;;
      2) echo "  <circle cx=\"$(( w * 46 / 100 ))\" cy=\"$(( h * 46 / 100 ))\" r=\"$(( h * 28 / 100 ))\" fill=\"$tone\" opacity=\"0.45\"/>"
         echo "  <circle cx=\"$(( w * 78 / 100 ))\" cy=\"$(( h * 76 / 100 ))\" r=\"$(( h * 16 / 100 ))\" fill=\"$tone\" opacity=\"0.32\"/>" ;;
      *) echo "  <rect x=\"0\" y=\"0\" width=\"$(( w * 40 / 100 ))\" height=\"$h\" fill=\"$tone\" opacity=\"0.28\"/>"
         echo "  <circle cx=\"$(( w * 66 / 100 ))\" cy=\"$(( h * 52 / 100 ))\" r=\"$(( h * 30 / 100 ))\" fill=\"$tone\" opacity=\"0.5\"/>" ;;
    esac
    echo "</svg>"
  } > "$svg"
  rsvg-convert -w "$w" -h "$h" "$svg" -o "$out"
  rm -f "$svg"
  printf "  %-40s %sx%s  art\n" "${out#$ROOT/}" "$w" "$h"
}

# make_label <out.png> <w> <h> <label> [subtitle] [anchor: center|left] [font-size]
#
# The optional font size overrides the height-derived default (used for the card
# image, which is drawn larger than the banner so it reads at card width).
#
# `left` exists for the banner. On the Android agent profile the circular logo
# avatar is overlaid on the banner's BOTTOM-CENTER, so anything centered there
# is covered on the one surface the banner appears on. Observed on hardware.
# Left-anchored, vertically centered text stays clear.
make_label() {
  local out="$1" w="$2" h="$3" label subtitle anchor svg fs sfs x align
  label="$(esc "$4")"; subtitle="$(esc "${5:-}")"; anchor="${6:-center}"
  svg="$(mktemp -t ah_svg.XXXXXX).svg"
  fs=$(( h / 9 )); [ "$fs" -gt 96 ] && fs=96; [ "$fs" -lt 18 ] && fs=18
  [ -n "${7:-}" ] && fs="$7"
  sfs=$(( fs * 5 / 9 ))
  if [ "$anchor" = "left" ]; then x="6%"; align="start"; else x="50%"; align="middle"; fi
  {
    echo "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$w\" height=\"$h\" viewBox=\"0 0 $w $h\">"
    echo "  <rect width=\"$w\" height=\"$h\" fill=\"$ACCENT\"/>"
    echo "  <text x=\"$x\" y=\"44%\" fill=\"#ffffff\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"$fs\" font-weight=\"700\" text-anchor=\"$align\" dominant-baseline=\"middle\">$label</text>"
    if [ -n "$subtitle" ]; then
      echo "  <text x=\"$x\" y=\"44%\" dy=\"$fs\" fill=\"#cfeceb\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"$sfs\" font-weight=\"400\" text-anchor=\"$align\" dominant-baseline=\"middle\">$subtitle</text>"
    fi
    echo "</svg>"
  } > "$svg"
  rsvg-convert -w "$w" -h "$h" "$svg" -o "$out"
  rm -f "$svg"
  printf "  %-40s %sx%s  label\n" "${out#$ROOT/}" "$w" "$h"
}

# make_logo <out.png> <size> <monogram>
#
# A circle on a TRANSPARENT field, not a full-bleed square. RCS requires the
# logo be a PNG with alpha, and both platforms render it circular in the thread
# and on the agent profile — a square field simply loses its corners.
make_logo() {
  local out="$1" size="$2" mono svg fs r
  mono="$(esc "$3")"
  r=$(( size / 2 ))
  fs=$(( size * 52 / 100 ))
  svg="$(mktemp -t ah_svg.XXXXXX).svg"
  {
    echo "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"$size\" height=\"$size\" viewBox=\"0 0 $size $size\">"
    echo "  <circle cx=\"$r\" cy=\"$r\" r=\"$r\" fill=\"$ACCENT\"/>"
    echo "  <text x=\"50%\" y=\"52%\" fill=\"#ffffff\" font-family=\"Helvetica, Arial, sans-serif\" font-size=\"$fs\" font-weight=\"700\" text-anchor=\"middle\" dominant-baseline=\"middle\">$mono</text>"
    echo "</svg>"
  } > "$svg"
  rsvg-convert -w "$size" -h "$size" "$svg" -o "$out"
  rm -f "$svg"
  printf "  %-40s %sx%s  logo (alpha)\n" "${out#$ROOT/}" "$size" "$size"
}

echo "Generating placeholder assets (accent $ACCENT)"

# Registration-critical (exact sizes), generated PER BRAND into that brand's own
# media/<id>/ folder from its catalog block. A brand's accentColor drives both
# its logo disc and its banner field; the monogram comes from its brandName and
# the banner subtitle from its tagline. Wordmarks belong here (unlike the shared
# wordless tiles below).
BRAND_IDS="$(brand_ids)"
[ -z "$BRAND_IDS" ] && { echo "ERROR: no brands found in $BRAND_MD (expected a 'brands:' map)"; exit 1; }
for bid in $BRAND_IDS; do
  bname="$(read_brand_key "$bid" brandName)";   [ -z "$bname" ] && bname="$bid"
  bacc="$(read_brand_key "$bid" accentColor)";  [ -z "$bacc" ] && bacc="#0B6E6F"
  btag="$(read_brand_key "$bid" tagline)"
  blogo="$(read_brand_key "$bid" logoImage)";   [ -z "$blogo" ] && blogo="media/$bid/logo.png"
  bbanner="$(read_brand_key "$bid" bannerImage)"; [ -z "$bbanner" ] && bbanner="media/$bid/banner.png"
  mkdir -p "$ROOT/$(dirname "$blogo")" "$ROOT/$(dirname "$bbanner")"
  ACCENT="$bacc"   # make_logo / make_label read the global ACCENT
  make_logo  "$ROOT/$blogo"   224 "$(monogram "$bname")"
  make_label "$ROOT/$bbanner" 1440 448 "$bname" "$btag" left
  # The card image: the picture on the welcome, home menu and check-in cards.
  # Separate from the banner because the two are cropped differently. The banner
  # is left-anchored to stay clear of the Android avatar; a card is cropped to
  # its centre, and a handset that shows a card narrower than 3:1 cuts the sides.
  # So this is 3:1 (1440x480, the SHORT card size) with the wordmark and tagline
  # centred inside the middle 960px, which survives a 2:1 centre crop.
  bcard="$(read_brand_key "$bid" cardImage)"; [ -z "$bcard" ] && bcard="media/$bid/card.png"
  mkdir -p "$ROOT/$(dirname "$bcard")"
  make_label "$ROOT/$bcard" 1440 480 "$bname" "$btag" center 88
done
ACCENT="#0B6E6F"   # restore the default for the shared assets below

# The default brand themes the single shared, branded asset (the favicon).
DEFAULT_BRAND="$(read_top_scalar defaultBrand)"; [ -z "$DEFAULT_BRAND" ] && DEFAULT_BRAND="anyhealth"
DEF_NAME="$(read_brand_key "$DEFAULT_BRAND" brandName)"; [ -z "$DEF_NAME" ] && DEF_NAME="AnyHealth"
DEF_ACCENT="$(read_brand_key "$DEFAULT_BRAND" accentColor)"; [ -z "$DEF_ACCENT" ] && DEF_ACCENT="#0B6E6F"
DEF_MONO="$(monogram "$DEF_NAME")"


# Healthcare rich-card tiles (3:2). Wordless — the card
# Title already says what each one is.
make_art "$MEDIA/appointment.png" 1080 720 0 0
make_art "$MEDIA/rx-refill.png"   1080 720 1 1
make_art "$MEDIA/benefits.png"    1080 720 2 2
make_art "$MEDIA/find-care.png"   1080 720 3 3

# Store product tiles (3:2). These duplicated the most: the baked label
# repeated the card Title and the baked price repeated the Description.
make_art "$STORE/mega-ice-pack.png"        1080 720 4 0
make_art "$STORE/calming-book.png"         1080 720 5 1
make_art "$STORE/medicine-spoon.png"       1080 720 6 2
make_art "$STORE/sleep-sound-machine.png"  1080 720 7 3
make_art "$STORE/herbal-tea-sampler.png"   1080 720 8 0

# Vignette tiles
make_art "$MEDIA/otp.png"             1080 720 9 1
make_art "$MEDIA/handover.png"        1080 720 2 3
make_art "$MEDIA/order-confirmed.png" 1080 720 4 2

# Internal staff vignette tiles (3:2)
make_art "$MEDIA/clock.png"      1080 720 3 0
make_art "$MEDIA/schedule.png"   1080 720 5 2
make_art "$MEDIA/pto.png"        1080 720 6 1
make_art "$MEDIA/shift-swap.png" 1080 720 7 3

# Rich-media demo tiles (3:2)
make_art "$MEDIA/photo-submission.png" 1080 720 8 2
make_art "$MEDIA/insurance-upload.png" 1080 720 9 0

# AnyBuild tiles (3:2), one per vignette card that carries a picture. The
# delivery-drop tile stands in for the driver's drop photo.
AB="$MEDIA/anybuild"
mkdir -p "$AB"
make_art "$AB/evidence.png"      1080 720 6 0
make_art "$AB/identity.png"      1080 720 8 1
make_art "$AB/arrival.png"       1080 720 3 2
make_art "$AB/delivery-drop.png" 1080 720 7 3
make_art "$AB/field-plan.png"    1080 720 5 0
make_art "$AB/readiness.png"     1080 720 2 1

# Dashboard favicon — a wordmark is correct here; nothing renders beside it.
ACCENT="$DEF_ACCENT"
make_label "$WEBPUB/favicon.png" 256 256 "$DEF_MONO"

echo "Done."
